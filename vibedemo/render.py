"""Render Kubernetes manifests from a validated contract.

This is the platform's golden path: the AI never writes Kubernetes YAML, it
only fills the contract. The output is deterministic (same input -> same files).
JSON-encoded strings are valid YAML, so no YAML library is needed.
"""

from __future__ import annotations

import json
from pathlib import Path

from .contract import SIZES

LABEL_PREFIX = "vibedemo.nutanix.com"


def _q(value) -> str:
    return json.dumps(str(value))


def common_labels(c: dict, sha: str) -> dict:
    labels = {
        "app.kubernetes.io/name": c["app"],
        "app.kubernetes.io/managed-by": "vibedemo",
        LABEL_PREFIX + "/managed": "true",
        LABEL_PREFIX + "/owner": c["owner"],
        LABEL_PREFIX + "/env": c["env"],
        LABEL_PREFIX + "/size": c["size"],
        LABEL_PREFIX + "/protection": c["protection"],
        LABEL_PREFIX + "/tracing": "true" if c["tracing"] else "false",
        LABEL_PREFIX + "/sha": sha,
    }
    if c.get("cost_center"):
        labels[LABEL_PREFIX + "/cost-center"] = c["cost_center"]
    if c.get("expires"):
        labels[LABEL_PREFIX + "/expires"] = c["expires"]
    return labels


def _labels_block(labels: dict, indent: int) -> str:
    pad = " " * indent
    return "\n".join("%s%s: %s" % (pad, k, _q(v)) for k, v in sorted(labels.items()))


def render_deployment(c: dict, image: str, sha: str, namespace: str) -> str:
    size = SIZES[c["size"]]
    labels = common_labels(c, sha)
    return """apiVersion: apps/v1
kind: Deployment
metadata:
  name: {name}
  namespace: {ns}
  labels:
{labels4}
spec:
  replicas: {replicas}
  revisionHistoryLimit: 3
  progressDeadlineSeconds: 180
  selector:
    matchLabels:
      app.kubernetes.io/name: {name}
  template:
    metadata:
      labels:
{labels8}
    spec:
      securityContext:
        runAsNonRoot: true
        seccompProfile:
          type: RuntimeDefault
      containers:
        - name: app
          image: {image}
          imagePullPolicy: IfNotPresent
          ports:
            - name: http
              containerPort: {port}
          resources:
            requests:
              cpu: {rcpu}
              memory: {rmem}
            limits:
              cpu: {lcpu}
              memory: {lmem}
          readinessProbe:
            httpGet:
              path: /
              port: http
            initialDelaySeconds: 1
            periodSeconds: 3
          livenessProbe:
            httpGet:
              path: /
              port: http
            initialDelaySeconds: 5
            periodSeconds: 10
          securityContext:
            allowPrivilegeEscalation: false
            capabilities:
              drop: ["ALL"]
""".format(
        name=_q(c["app"]), ns=_q(namespace), labels4=_labels_block(labels, 4),
        labels8=_labels_block(labels, 8), replicas=c["replicas"], image=_q(image),
        port=c["port"], rcpu=_q(size["requests"]["cpu"]), rmem=_q(size["requests"]["memory"]),
        lcpu=_q(size["limits"]["cpu"]), lmem=_q(size["limits"]["memory"]))


def render_service(c: dict, sha: str, namespace: str) -> str:
    labels = common_labels(c, sha)
    return """apiVersion: v1
kind: Service
metadata:
  name: {name}
  namespace: {ns}
  labels:
{labels4}
spec:
  type: LoadBalancer
  selector:
    app.kubernetes.io/name: {name}
  ports:
    - name: http
      port: 80
      targetPort: http
""".format(name=_q(c["app"]), ns=_q(namespace), labels4=_labels_block(labels, 4))


HEADER = ("# GENERATED by the platform golden path from contract.yaml - DO NOT EDIT.\n"
          "# Source commit: {sha}\n")


def render_all(c: dict, image: str, sha: str, namespace: str) -> dict:
    """Return {filename: content} for the deploy/ directory."""
    header = HEADER.format(sha=sha)
    return {
        "app.yaml": header + render_deployment(c, image, sha, namespace)
                    + "---\n" + render_service(c, sha, namespace),
        "kustomization.yaml": header + "apiVersion: kustomize.config.k8s.io/v1beta1\n"
                              "kind: Kustomization\nresources:\n  - app.yaml\n",
    }


def write_deploy_dir(out_dir, files: dict) -> list:
    """Replace the content of out_dir with files. Returns written paths."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    for old in out.iterdir():
        if old.is_file() and old.suffix in (".yaml", ".yml"):
            old.unlink()
    written = []
    for name, content in sorted(files.items()):
        path = out / name
        path.write_text(content, encoding="utf-8")
        written.append(str(path))
    return written
